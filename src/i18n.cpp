std::string language() {
    std::string lang = Config::get().language;
    std::transform(lang.begin(), lang.end(), lang.begin(),
                   [](unsigned char c) { return static_cast<char>(std::tolower(c)); });
    return lang == "es" ? "es" : "en";
}

