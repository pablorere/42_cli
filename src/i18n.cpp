std::string tr(const std::string& key) {
    const auto& t = (language() == "es") ? table_es() : table_en();
    auto it = t.find(key);
    if (it != t.end()) return it->second;
    auto en = table_en().find(key);
    return en != table_en().end() ? en->second : key;
}

